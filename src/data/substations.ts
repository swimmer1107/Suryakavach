export const getSubstationById = (id: string): Substation | undefined => 
  substations.find(s => s.id === id);

export const getSubstationsByStatus = (status: string): Substation[] =>
  substations.filter(s => s.status === status);

export const getCriticalCount = (): number =>
  substations.filter(s => s.status === 'critical').length;

export const getHighCount = (): number =>
  substations.filter(s => s.status === 'high').length;

export const getModerateCount = (): number =>
  substations.filter(s => s.status === 'moderate').length;

export const getSafeCount = (): number =>
  substations.filter(s => s.status === 'safe').length;

export const getAffectedCount = (): number =>
  substations.filter(s => s.status === 'critical' || s.status === 'high').length;
